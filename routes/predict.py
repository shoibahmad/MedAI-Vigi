"""
Prediction and Inference Routes for ADR Risk Stratification
"""

from typing import Any, Dict, Tuple

from flask import Blueprint, Response, jsonify, request
from pydantic import ValidationError

from schemas import PatientDataSchema
from services.clinical_service import ClinicalService
from services.gemini_service import GeminiService
from services.ml_service import MLService, ModelNotReadyError

predict_bp = Blueprint("predict", __name__)


@predict_bp.route("/predict", methods=["POST"])
def predict() -> Tuple[Response, int]:
    """Execute ML prediction and return comprehensive ADR risk analysis"""
    if not request.is_json:
        return jsonify({"status": "error", "message": "Request must be JSON"}), 400

    raw_data = request.get_json()
    if not raw_data:
        return jsonify({"status": "error", "message": "Empty JSON payload"}), 400

    # Validate schema with Pydantic
    try:
        validated_schema = PatientDataSchema(**raw_data)
        patient_dict = validated_schema.model_dump()
    except ValidationError as e:
        return jsonify({"status": "validation_error", "errors": e.errors()}), 422
    except Exception as e:
        return jsonify({"status": "error", "message": str(e)}), 400

    # Execute ML inference
    ml_service = MLService.get_instance()
    try:
        result = ml_service.predict(patient_dict)
        return jsonify(result), 200
    except ModelNotReadyError as e:
        return jsonify({"status": "error", "message": str(e)}), 503
    except Exception as e:
        return jsonify({"status": "error", "message": f"Inference failed: {str(e)}"}), 500


@predict_bp.route("/mitigation_strategies", methods=["POST"])
def mitigation_strategies() -> Tuple[Response, int]:
    """
    Risk-prioritized mitigation plan.

    Previously a fixed list keyed only off risk_level, identical for every
    patient. Now generated by Gemini from the full clinical picture, with the
    original list retained as the offline fallback.
    """
    data = request.get_json() or {}
    patient_data = data.get("patient_data", {})
    prediction_result = data.get("prediction_result", {})

    gemini_service = GeminiService.get_instance()
    result = gemini_service.generate_mitigation_strategies(
        patient_data=patient_data, prediction_result=prediction_result
    )

    return jsonify({"status": "success", **result}), 200


