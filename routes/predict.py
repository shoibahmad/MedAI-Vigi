@predict_bp.route("/get_drug_adrs", methods=["GET"])
def get_drug_adrs() -> Tuple[Response, int]:
    """Return known adverse drug reactions for medication query"""
    drug = request.args.get("drug", "Warfarin")
    adrs = ClinicalService.get_comprehensive_adr_list(drug)
    return jsonify({"drug": drug, "known_adrs": adrs}), 200
